package protocolgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

const agentHeader = "// Code generated by tools/gen from protocol/agent/. DO NOT EDIT.\n\n"

// AgentFiles are the exported agent texts: the one agent-neutral instruction text, the Teamflow command's body, and
// the teamflow commands an agent runs (commands.json).
type AgentFiles struct {
	Instructions, Teamf, Commands []byte
}

// commandName is a command's words: lower case, separated by single spaces.
var commandName = regexp.MustCompile(`^[a-z][a-z0-9-]*( [a-z][a-z0-9-]*)*$`)

type agentCommand struct {
	Name          string  `json:"name"`
	Usage         string  `json:"usage"`
	Description   string  `json:"description"`
	Consequential bool    `json:"consequential"`
	Input         *string `json:"input"`
	Help          *string `json:"help"`
	New           bool    `json:"new"`
}

// readCommands reads commands.json: {about, every_command, commands: [...]}, each command checked.
func readCommands(raw []byte) ([]agentCommand, error) {
	var doc struct {
		About        json.RawMessage `json:"about"`
		EveryCommand json.RawMessage `json:"every_command"`
		Commands     json.RawMessage `json:"commands"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		return nil, fmt.Errorf("agent/commands.json: %w", err)
	}
	dec := json.NewDecoder(bytes.NewReader(doc.Commands))
	dec.DisallowUnknownFields()
	var cmds []agentCommand
	if err := dec.Decode(&cmds); err != nil {
		return nil, fmt.Errorf("agent/commands.json: commands: %w", err)
	}
	if len(cmds) == 0 {
		return nil, fmt.Errorf("agent/commands.json: no commands")
	}
	seen := map[string]bool{}
	for i, c := range cmds {
		input, help := "", ""
		if c.Input != nil {
			input = *c.Input
		}
		if c.Help != nil {
			help = *c.Help
		}
		switch {
		case c.Name == "":
			return nil, fmt.Errorf("agent/commands.json: command %d without a name", i+1)
		case !commandName.MatchString(c.Name):
			return nil, fmt.Errorf("agent/commands.json: %q is not a command name", c.Name)
		case seen[c.Name]:
			return nil, fmt.Errorf("agent/commands.json: %s twice", c.Name)
		case c.Usage != "teamflow "+c.Name && !strings.HasPrefix(c.Usage, "teamflow "+c.Name+" "):
			return nil, fmt.Errorf("agent/commands.json: %s: its usage must start with `teamflow %s`", c.Name, c.Name)
		case strings.TrimSpace(c.Description) == "":
			return nil, fmt.Errorf("agent/commands.json: %s has no description", c.Name)
		case input != "" && input != "json":
			return nil, fmt.Errorf("agent/commands.json: %s: input is %q, not json or null", c.Name, input)
		case input == "json" && strings.TrimSpace(help) == "":
			return nil, fmt.Errorf("agent/commands.json: %s takes JSON but has no help", c.Name)
		case input == "" && c.Help != nil:
			return nil, fmt.Errorf("agent/commands.json: %s takes no JSON but has help", c.Name)
		}
		seen[c.Name] = true
	}
	return cmds, nil
}

// GenerateAgent returns agent_gen.go: the texts word for word and the commands in commands.json's order.
func GenerateAgent(f AgentFiles) ([]byte, error) {
	if strings.TrimSpace(string(f.Instructions)) == "" {
		return nil, fmt.Errorf("agent/instructions.md is empty")
	}
	if strings.TrimSpace(string(f.Teamf)) == "" {
		return nil, fmt.Errorf("agent/teamf.md is empty")
	}
	cmds, err := readCommands(f.Commands)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString(agentHeader + "package protocol\n\n")
	b.WriteString("// AgentInstructions is the one agent-neutral instruction text (protocol/agent/instructions.md), word for word.\n")
	fmt.Fprintf(&b, "const AgentInstructions = %s\n\n", strconv.Quote(string(f.Instructions)))
	b.WriteString("// AgentTeamf is the Teamflow command's body (protocol/agent/teamf.md): an adapter fills in {TEAMFLOW} and\n// {ARGUMENTS}.\n")
	fmt.Fprintf(&b, "const AgentTeamf = %s\n\n", strconv.Quote(string(f.Teamf)))
	b.WriteString("// AgentCommand is one teamflow command an agent runs (protocol/agent/commands.json): its usage line, what it\n" +
		"// does, whether it is consequential (only on the person's explicit words), its input (\"json\": a document from\n" +
		"// --file, whose shape Help gives, word for word), and whether it was new to the Go client.\n" +
		"type AgentCommand struct {\n\tName, Usage, Description string\n\tConsequential bool\n\tInput, Help string\n\tNew bool\n}\n\n")
	b.WriteString("// AgentCommands are the commands an agent runs, in commands.json's order.\nvar AgentCommands = []AgentCommand{\n")
	for _, c := range cmds {
		input, help := "", ""
		if c.Input != nil {
			input = *c.Input
		}
		if c.Help != nil {
			help = *c.Help
		}
		fmt.Fprintf(&b, "\t{Name: %s, Usage: %s, Description: %s, Consequential: %t, Input: %s, Help: %s, New: %t},\n",
			strconv.Quote(c.Name), strconv.Quote(c.Usage), strconv.Quote(c.Description), c.Consequential,
			strconv.Quote(input), strconv.Quote(help), c.New)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("agent_gen.go: %w", err)
	}
	return src, nil
}

// WriteAll generates every file of package protocol from the export folder into dir.
func WriteAll(protocolDir, dir string) error {
	read := func(name string) ([]byte, error) { return os.ReadFile(filepath.Join(protocolDir, name)) }
	schema, err := read("schema.json")
	if err != nil {
		return err
	}
	methods, err := read("methods.json")
	if err != nil {
		return err
	}
	var f AgentFiles
	for _, x := range []struct {
		name string
		into *[]byte
	}{
		{filepath.Join("agent", "instructions.md"), &f.Instructions},
		{filepath.Join("agent", "teamf.md"), &f.Teamf},
		{filepath.Join("agent", "commands.json"), &f.Commands},
	} {
		if *x.into, err = read(x.name); err != nil {
			return err
		}
	}
	agent, err := GenerateAgent(f)
	if err != nil {
		return err
	}
	if err := WriteFiles(dir, schema, methods); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "agent_gen.go"), agent, 0o644)
}
