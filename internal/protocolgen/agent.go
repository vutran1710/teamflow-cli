package protocolgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

const agentHeader = "// Code generated by tools/gen from protocol/agent/ and protocol/mcp_tools.json. DO NOT EDIT.\n\n"

// AgentFiles are the exported agent texts: the one agent-neutral instruction text, the Teamflow command's body, the
// MCP tools' names and descriptions, and the Python MCP server's input schemas (mcp_tools.json).
type AgentFiles struct {
	Instructions, Teamf, Tools, MCPTools []byte
}

var toolName = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

// GenerateAgent returns agent_gen.go: the texts word for word, the tools in tools.json's order, and the Python
// input schema of each tool that has one.
func GenerateAgent(f AgentFiles) ([]byte, error) {
	if strings.TrimSpace(string(f.Instructions)) == "" {
		return nil, fmt.Errorf("agent/instructions.md is empty")
	}
	if strings.TrimSpace(string(f.Teamf)) == "" {
		return nil, fmt.Errorf("agent/teamf.md is empty")
	}
	var tools []struct {
		Name        string `json:"name"`
		Description string `json:"description"`
	}
	if err := json.Unmarshal(f.Tools, &tools); err != nil {
		return nil, fmt.Errorf("agent/tools.json: %w", err)
	}
	if len(tools) == 0 {
		return nil, fmt.Errorf("agent/tools.json: no tools")
	}
	seen := map[string]bool{}
	for i, t := range tools {
		switch {
		case t.Name == "":
			return nil, fmt.Errorf("agent/tools.json: tool %d without a name", i+1)
		case !toolName.MatchString(t.Name):
			return nil, fmt.Errorf("agent/tools.json: %q is not a tool name", t.Name)
		case seen[t.Name]:
			return nil, fmt.Errorf("agent/tools.json: %s twice", t.Name)
		case strings.TrimSpace(t.Description) == "":
			return nil, fmt.Errorf("agent/tools.json: %s has no description", t.Name)
		}
		seen[t.Name] = true
	}
	var mcp []struct {
		Name   string          `json:"name"`
		Schema json.RawMessage `json:"input_schema"`
	}
	if err := json.Unmarshal(f.MCPTools, &mcp); err != nil {
		return nil, fmt.Errorf("mcp_tools.json: %w", err)
	}
	schemas := map[string]string{}
	for _, m := range mcp {
		var head struct {
			Type string `json:"type"`
		}
		if json.Unmarshal(m.Schema, &head) != nil || head.Type != "object" {
			return nil, fmt.Errorf("mcp_tools.json: %s: not an object schema", m.Name)
		}
		if !seen[m.Name] {
			return nil, fmt.Errorf("mcp_tools.json: %s is not in tools.json", m.Name)
		}
		var compact bytes.Buffer
		if err := json.Compact(&compact, m.Schema); err != nil {
			return nil, fmt.Errorf("mcp_tools.json: %s: %w", m.Name, err)
		}
		schemas[m.Name] = compact.String()
	}

	var b strings.Builder
	b.WriteString(agentHeader + "package protocol\n\n")
	b.WriteString("// AgentInstructions is the one agent-neutral instruction text (protocol/agent/instructions.md), word for word.\n")
	fmt.Fprintf(&b, "const AgentInstructions = %s\n\n", strconv.Quote(string(f.Instructions)))
	b.WriteString("// AgentTeamf is the Teamflow command's body (protocol/agent/teamf.md): an adapter fills in {TEAMFLOW} and\n// {ARGUMENTS}.\n")
	fmt.Fprintf(&b, "const AgentTeamf = %s\n\n", strconv.Quote(string(f.Teamf)))
	b.WriteString("// AgentTool is one MCP tool as every agent is given it.\ntype AgentTool struct {\n\tName, Description string\n}\n\n")
	b.WriteString("// AgentTools are the MCP tools (protocol/agent/tools.json), in order.\nvar AgentTools = []AgentTool{\n")
	for _, t := range tools {
		fmt.Fprintf(&b, "\t{Name: %s, Description: %s},\n", strconv.Quote(t.Name), strconv.Quote(t.Description))
	}
	b.WriteString("}\n\n")
	b.WriteString("// PythonInputSchemas are the input schemas of the tools the Python MCP server had (protocol/mcp_tools.json), as\n// JSON, by tool name.\nvar PythonInputSchemas = map[string]string{\n")
	for _, t := range tools { // tools.json's order: stable output
		s, ok := schemas[t.Name]
		if !ok {
			continue
		}
		lit := "`" + s + "`"
		if strings.Contains(s, "`") {
			lit = strconv.Quote(s)
		}
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(t.Name), lit)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("agent_gen.go: %w", err)
	}
	return src, nil
}

// WriteAll generates every file of package protocol from the export folder into dir.
func WriteAll(protocolDir, dir string) error {
	read := func(name string) ([]byte, error) { return os.ReadFile(filepath.Join(protocolDir, name)) }
	schema, err := read("schema.json")
	if err != nil {
		return err
	}
	methods, err := read("methods.json")
	if err != nil {
		return err
	}
	var f AgentFiles
	for _, x := range []struct {
		name string
		into *[]byte
	}{
		{filepath.Join("agent", "instructions.md"), &f.Instructions},
		{filepath.Join("agent", "teamf.md"), &f.Teamf},
		{filepath.Join("agent", "tools.json"), &f.Tools},
		{"mcp_tools.json", &f.MCPTools},
	} {
		if *x.into, err = read(x.name); err != nil {
			return err
		}
	}
	agent, err := GenerateAgent(f)
	if err != nil {
		return err
	}
	if err := WriteFiles(dir, schema, methods); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "agent_gen.go"), agent, 0o644)
}
