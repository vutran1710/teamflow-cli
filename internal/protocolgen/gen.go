// Package protocolgen turns the exported Teamflow protocol (protocol/schema.json and protocol/methods.json) into
// the Go types of package protocol. tools/gen runs it; a contract test runs it again and fails when the committed
// output is stale.
//
// Mapping:
//   - an object $def becomes a struct with the schema's field names and order. A field that is optional with no
//     default is a pointer (or map, slice) with omitempty; every other field is always encoded.
//   - decoding fills each missing field with its schema default; encoding turns nil slices and maps into [] and {},
//     and an empty const field (a union tag) into its const.
//   - a string enum $def becomes a named string type and its values constants.
//   - a union (oneOf/anyOf of several $defs, or one with a discriminator) becomes an interface with a Decode
//     function. The variant is picked by the discriminator, else by a const field every variant has, else by a
//     required field only that variant has. A variant this client doesn't know decodes to Unknown<Union> holding
//     the raw JSON; it is never an error. A value missing its const tag is picked by shape only when exactly one
//     variant fits it exactly (closed variants: no field it doesn't have); otherwise it is unknown.
//   - every struct gets New<Def>(), holding the schema's defaults: the way to build a value to send.
//   - unknown JSON fields are ignored everywhere.
package protocolgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const header = "// Code generated by tools/gen from protocol/schema.json and protocol/methods.json. DO NOT EDIT.\n\n"

// special unions: SyncEvent is the interface the rest of the client is written against.
var specialUnions = map[string]unionNames{
	"SyncEvent": {method: "EventType() string", unknown: "UnknownEvent", tagField: "Type"},
}

// constant names that read better than the exported ones, emitted as aliases.
var constantAliases = map[string]struct{ name, doc string }{
	"LIVE_PONG_SECONDS": {"LiveSilenceSeconds", "seconds of silence after a ping that mean the socket is dead"},
}

