var constantPrefixes = map[string]string{"RPC_ERROR_CODES": "Code"}

// WriteFiles generates into dir.
func WriteFiles(dir string, schema, methods []byte) error {
	files, err := Generate(schema, methods)
	if err != nil {
		return err
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if err := os.WriteFile(filepath.Join(dir, n), files[n], 0o644); err != nil {
			return err
		}
	}
	return nil
}

// Generate returns the generated files by name.
func Generate(schema, methods []byte) (map[string][]byte, error) {
	root, err := parseOrdered(schema)
	if err != nil {
		return nil, fmt.Errorf("schema.json: %w", err)
	}
	doc, ok := root.(*object)
	if !ok {
		return nil, fmt.Errorf("schema.json: not an object")
	}
	defs, ok := doc.get("$defs").(*object)
	if !ok || len(defs.keys) == 0 {
		return nil, fmt.Errorf("schema.json: no $defs")
	}
	g := &gen{defs: defs, unions: map[string]*union{}, unionByCanon: map[string]string{}}
	types, err := g.types()
	if err != nil {
		return nil, err
	}
	consts, err := constants(doc.get("x-constants"), methods)
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{}
	for name, body := range map[string]string{"types_gen.go": types, "constants_gen.go": consts} {
		src, err := format.Source([]byte(body))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		out[name] = src
	}
	return out, nil
}

// ---------------------------------------------------------------- ordered JSON

// object is a JSON object that keeps its key order (the schema's field order).
type object struct {
	keys []string
	vals map[string]any
}

func (o *object) get(k string) any {
	if o == nil {
		return nil
	}
	return o.vals[k]
}

func (o *object) has(k string) bool {
	if o == nil {
		return false
	}
	_, ok := o.vals[k]
	return ok
}

func parseOrdered(b []byte) (any, error) {
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.UseNumber()
	v, err := parseValue(dec)
	if err != nil {
		return nil, err
	}
	if _, err := dec.Token(); err == nil {
		return nil, fmt.Errorf("trailing data")
	}
	return v, nil
}

func parseValue(dec *json.Decoder) (any, error) {
	tok, err := dec.Token()
	if err != nil {
		return nil, err
	}
	switch t := tok.(type) {
	case json.Delim:
		switch t {
		case '{':
			o := &object{vals: map[string]any{}}
			for dec.More() {
				kt, err := dec.Token()
				if err != nil {
					return nil, err
				}
				k := kt.(string)
				v, err := parseValue(dec)
				if err != nil {
					return nil, err
				}
				if _, dup := o.vals[k]; !dup {
					o.keys = append(o.keys, k)
				}
				o.vals[k] = v
			}
			_, err := dec.Token()
			return o, err
		case '[':
			arr := []any{}
			for dec.More() {
				v, err := parseValue(dec)
				if err != nil {
					return nil, err
				}
				arr = append(arr, v)
			}
			_, err := dec.Token()
			return arr, err
		}
		return nil, fmt.Errorf("unexpected %v", t)
	default:
		return tok, nil
	}
}

// plainJSON converts an ordered value back to plain Go values (sorted keys when encoded).
func plainJSON(v any) any {
	switch x := v.(type) {
	case *object:
		m := map[string]any{}
		for _, k := range x.keys {
			m[k] = plainJSON(x.vals[k])
		}
		return m
	case []any:
		out := make([]any, len(x))
		for i, e := range x {
			out[i] = plainJSON(e)
		}
		return out
	default:
		return v
	}
}

// ---------------------------------------------------------------- names

var initialisms = map[string]string{"id": "ID", "url": "URL", "rpc": "RPC", "http": "HTTP", "api": "API",
	"json": "JSON", "uri": "URI", "ip": "IP"}

var wordSplit = regexp.MustCompile(`[^A-Za-z0-9]+`)

// goName turns snake_case, SCREAMING_CASE and dotted.names into CamelCase.
func goName(s string) string {
	var b strings.Builder
	for _, part := range wordSplit.Split(s, -1) {
		if part == "" {
			continue
		}
		if up, ok := initialisms[strings.ToLower(part)]; ok {
			b.WriteString(up)
			continue
		}
		if strings.ToUpper(part) == part {
			part = strings.ToLower(part)
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	out := b.String()
	if out == "" || (out[0] >= '0' && out[0] <= '9') {
		out = "X" + out
	}
	return out
}

func comment(name string, desc any) string {
	d, _ := desc.(string)
	d = strings.TrimSpace(d)
	if d == "" {
		return ""
	}
	var b strings.Builder
	for i, line := range strings.Split(d, "\n") {
		if i == 0 {
			line = name + ": " + line
		}
		b.WriteString(strings.TrimRight("// "+line, " ") + "\n")
	}
	return b.String()
}

// ---------------------------------------------------------------- types

type kind int

const (
	kScalar kind = iota
	kEnum
	kStruct
	kUnion
	kSlice
	kMap
	kPtr
)

type typeInfo struct {
	goType string
	kind   kind
	elem   *typeInfo
	union  string
}

type union struct {
	name     string
	names    unionNames
	tagProp  string            // the field that names the variant ("" when picked by a required field)
	byShape  bool              // without its tag field, a value is picked by its required fields
	variants []string          // struct names, in schema order
	tags     map[string]string // variant -> tag
	markers  map[string]string // variant -> its own required field (tagProp == "")
	desc     any
}

type unionNames struct{ method, unknown, tagField string }

type field struct {
	key, name string
	t         typeInfo
	required  bool
	def       any
	hasDef    bool
	constVal  string
	omitEmpty bool
}

type gen struct {
	defs         *object
	unions       map[string]*union
	unionByCanon map[string]string
}

func (g *gen) def(name string) (*object, error) {
	d, ok := g.defs.get(name).(*object)
	if !ok {
		return nil, fmt.Errorf("unknown $def %q", name)
	}
	return d, nil
}

func refName(node *object) (string, bool) {
	ref, ok := node.get("$ref").(string)
	if !ok {
		return "", false
	}
	return strings.TrimPrefix(ref, "#/$defs/"), true
}

func isUnion(node *object) bool { return node.has("oneOf") || node.has("anyOf") }

func isEnum(node *object) bool { return node.get("type") == "string" && node.has("enum") }

func (g *gen) types() (string, error) {
	sortedDefs := append([]string(nil), g.defs.keys...)
	sort.Strings(sortedDefs)
	// Unions named by $defs first, so inline copies of them (SyncBatch.events) reuse the name.
	for _, name := range sortedDefs {
		d, err := g.def(name)
		if err != nil {
			return "", err
		}
		if isUnion(d) {
			if _, err := g.registerUnion(name, d); err != nil {
				return "", fmt.Errorf("$def %s: %w", name, err)
			}
		}
	}
	var enums, structs strings.Builder
	var factories []string
	isStruct := map[string]bool{}
	for _, name := range sortedDefs {
		d, _ := g.def(name)
		switch {
		case isUnion(d):
			continue
		case isEnum(d):
			if err := g.emitEnum(&enums, name, d); err != nil {
				return "", fmt.Errorf("$def %s: %w", name, err)
			}
		case d.get("type") == "object":
			if err := g.emitStruct(&structs, name, d); err != nil {
				return "", fmt.Errorf("$def %s: %w", name, err)
			}
			isStruct[name] = true
		default:
			return "", fmt.Errorf("$def %s: unsupported (type %v)", name, d.get("type"))
		}
		factories = append(factories, name)
	}
	var unions strings.Builder
	unionNamesSorted := make([]string, 0, len(g.unions))
	for n := range g.unions {
		unionNamesSorted = append(unionNamesSorted, n)
	}
	sort.Strings(unionNamesSorted)
	for _, n := range unionNamesSorted {
		g.emitUnion(&unions, g.unions[n])
	}

	var body strings.Builder
	body.WriteString(enums.String())
	body.WriteString(unions.String())
	body.WriteString(structs.String())
	body.WriteString("// newDef gives a new value of the Go type of a $def (unions excepted), holding its defaults, or nil.\n")
	body.WriteString("func newDef(name string) any {\n\tswitch name {\n")
	for _, n := range factories {
		if isStruct[n] {
			fmt.Fprintf(&body, "\tcase %q:\n\t\tv := New%s()\n\t\treturn &v\n", n, n)
		} else {
			fmt.Fprintf(&body, "\tcase %q:\n\t\treturn new(%s)\n", n, n)
		}
	}
	body.WriteString("\t}\n\treturn nil\n}\n")

	src := body.String()
	var imports []string
	for _, pkg := range []string{"encoding/json", "fmt"} {
		if strings.Contains(src, filepath.Base(pkg)+".") {
			imports = append(imports, strconv.Quote(pkg))
		}
	}
	head := header + "package protocol\n\n"
	if len(imports) > 0 {
		head += "import (\n\t" + strings.Join(imports, "\n\t") + "\n)\n\n"
	}
	return head + src, nil
}

func (g *gen) emitEnum(b *strings.Builder, name string, d *object) error {
	values, ok := d.get("enum").([]any)
	if !ok || len(values) == 0 {
		return fmt.Errorf("enum without values")
	}
	b.WriteString(comment(name, d.get("description")))
	fmt.Fprintf(b, "type %s string\n\nconst (\n", name)
	seen := map[string]bool{}
	for _, v := range values {
		s, ok := v.(string)
		if !ok {
			return fmt.Errorf("enum value %v is not a string", v)
		}
		c := name + goName(s)
		if seen[c] {
			return fmt.Errorf("enum values collide as %s", c)
		}
		seen[c] = true
		fmt.Fprintf(b, "\t%s %s = %q\n", c, name, s)
	}
	b.WriteString(")\n\n")
	return nil
}

// canonical: a union's identity, without its title and description.
func canonical(node *object) string {
	m := plainJSON(node).(map[string]any)
	delete(m, "title")
	delete(m, "description")
	delete(m, "default")
	b, _ := json.Marshal(m)
	return string(b)
}

func (g *gen) registerUnion(name string, node *object) (string, error) {
	canon := canonical(node)
	if existing, ok := g.unionByCanon[canon]; ok {
		return existing, nil
	}
	if _, clash := g.unions[name]; clash || (g.defs.has(name) && !isUnion(g.defs.get(name).(*object))) {
		return "", fmt.Errorf("union name %s is taken", name)
	}
	var branches []any
	for _, key := range []string{"oneOf", "anyOf"} {
		if bs, ok := node.get(key).([]any); ok {
			branches = bs
		}
	}
	u := &union{name: name, tags: map[string]string{}, markers: map[string]string{}, desc: node.get("description")}
	if n, ok := specialUnions[name]; ok {
		u.names = n
	} else {
		u.names = unionNames{method: "is" + name + "()", unknown: "Unknown" + name, tagField: "Tag"}
	}
	for _, br := range branches {
		bo, ok := br.(*object)
		if !ok {
			return "", fmt.Errorf("a branch is not an object")
		}
		ref, ok := refName(bo)
		if !ok {
			return "", fmt.Errorf("a branch is not a $ref")
		}
		d, err := g.def(ref)
		if err != nil {
			return "", err
		}
		if d.get("type") != "object" {
			return "", fmt.Errorf("variant %s is not an object", ref)
		}
		u.variants = append(u.variants, ref)
	}
	if len(u.variants) == 0 {
		return "", fmt.Errorf("a union without variants")
	}
	switch {
	case node.has("discriminator"):
		disc := node.get("discriminator").(*object)
		u.tagProp, _ = disc.get("propertyName").(string)
		mapping, _ := disc.get("mapping").(*object)
		for _, tag := range mapping.keys {
			ref, _ := mapping.get(tag).(string)
			u.tags[strings.TrimPrefix(ref, "#/$defs/")] = tag
		}
	default:
		u.tagProp = g.commonConst(u.variants)
		u.byShape = u.tagProp != ""
		if u.tagProp != "" {
			for _, v := range u.variants {
				d, _ := g.def(v)
				u.tags[v] = d.get("properties").(*object).get(u.tagProp).(*object).get("const").(string)
			}
		}
	}
	if u.tagProp != "" {
		for _, v := range u.variants {
			if _, ok := u.tags[v]; !ok {
				return "", fmt.Errorf("variant %s has no tag", v)
			}
		}
	} else {
		for _, v := range u.variants {
			m, err := g.ownRequired(v, u.variants)
			if err != nil {
				return "", err
			}
			u.markers[v] = m
		}
	}
	g.unions[name] = u
	g.unionByCanon[canon] = name
	return name, nil
}

// commonConst: a property that is a string const in every variant.
func (g *gen) commonConst(variants []string) string {
	first, _ := g.def(variants[0])
	props, _ := first.get("properties").(*object)
	if props == nil {
		return ""
	}
	for _, p := range props.keys {
		all := true
		for _, v := range variants {
			d, _ := g.def(v)
			vp, _ := d.get("properties").(*object)
			pn, _ := vp.get(p).(*object)
			if _, ok := pn.get("const").(string); !ok {
				all = false
				break
			}
		}
		if all {
			return p
		}
	}
	return ""
}

func requiredOf(d *object) []string {
	var out []string
	if req, ok := d.get("required").([]any); ok {
		for _, r := range req {
			out = append(out, r.(string))
		}
	}
	return out
}

// ownRequired: a required field of v that no other variant has.
func (g *gen) ownRequired(v string, variants []string) (string, error) {
	d, _ := g.def(v)
	for _, r := range requiredOf(d) {
		own := true
		for _, other := range variants {
			if other == v {
				continue
			}
			od, _ := g.def(other)
			if props, ok := od.get("properties").(*object); ok && props.has(r) {
				own = false
			}
		}
		if own {
			return r, nil
		}
	}
	return "", fmt.Errorf("variant %s has no tag and no required field of its own", v)
}

func (g *gen) typeOf(node *object, ctx string) (typeInfo, error) {
	if ref, ok := refName(node); ok {
		d, err := g.def(ref)
		if err != nil {
			return typeInfo{}, err
		}
		switch {
		case isUnion(d):
			name, err := g.registerUnion(ref, d)
			return typeInfo{goType: name, kind: kUnion, union: name}, err
		case isEnum(d):
			return typeInfo{goType: ref, kind: kEnum}, nil
		default:
			return typeInfo{goType: ref, kind: kStruct}, nil
		}
	}
	if isUnion(node) {
		var branches []any
		for _, key := range []string{"oneOf", "anyOf"} {
			if bs, ok := node.get(key).([]any); ok {
				branches = bs
			}
		}
		var nonNull []*object
		nullable := false
		for _, br := range branches {
			bo, ok := br.(*object)
			if !ok {
				return typeInfo{}, fmt.Errorf("%s: a branch is not an object", ctx)
			}
			if bo.get("type") == "null" {
				nullable = true
				continue
			}
			nonNull = append(nonNull, bo)
		}
		if len(nonNull) == 1 && !node.has("discriminator") {
			inner, err := g.typeOf(nonNull[0], ctx)
			if err != nil || !nullable || inner.kind == kUnion {
				return inner, err // a union's nil is null
			}
			return typeInfo{goType: "*" + inner.goType, kind: kPtr, elem: &inner}, nil
		}
		if nullable {
			// A nullable union of several $defs: the union of the others; its nil is null.
			inner := &object{keys: []string{"anyOf"}, vals: map[string]any{}}
			var bs []any
			for _, n := range nonNull {
				bs = append(bs, n)
			}
			inner.vals["anyOf"] = bs
			if node.has("discriminator") {
				inner.keys = append(inner.keys, "discriminator")
				inner.vals["discriminator"] = node.get("discriminator")
			}
			node = inner
		}
		name, err := g.registerUnion(ctx, node)
		return typeInfo{goType: name, kind: kUnion, union: name}, err
	}
	if node.has("const") {
		if _, ok := node.get("const").(string); !ok {
			return typeInfo{}, fmt.Errorf("%s: a const that is not a string", ctx)
		}
		return typeInfo{goType: "string", kind: kScalar}, nil
	}
	switch node.get("type") {
	case "string":
		return typeInfo{goType: "string", kind: kScalar}, nil
	case "integer":
		return typeInfo{goType: "int64", kind: kScalar}, nil
	case "number":
		return typeInfo{goType: "float64", kind: kScalar}, nil
	case "boolean":
		return typeInfo{goType: "bool", kind: kScalar}, nil
	case "array":
		items, ok := node.get("items").(*object)
		if !ok {
			return typeInfo{}, fmt.Errorf("%s: an array without items", ctx)
		}
		elem, err := g.typeOf(items, ctx+"Item")
		if err != nil {
			return typeInfo{}, err
		}
		return typeInfo{goType: "[]" + elem.goType, kind: kSlice, elem: &elem}, nil
	case "object":
		if pats, ok := node.get("patternProperties").(*object); ok && len(pats.keys) > 0 {
			if len(pats.keys) != 1 {
				return typeInfo{}, fmt.Errorf("%s: several patternProperties", ctx)
			}
			elem, err := g.typeOf(pats.get(pats.keys[0]).(*object), ctx+"Value")
			if err != nil {
				return typeInfo{}, err
			}
			return mapOf(elem)
		}
		if addl, ok := node.get("additionalProperties").(*object); ok {
			elem, err := g.typeOf(addl, ctx+"Value")
			if err != nil {
				return typeInfo{}, err
			}
			return mapOf(elem)
		}
		if props, ok := node.get("properties").(*object); ok && len(props.keys) > 0 && node.get("additionalProperties") != true {
			return typeInfo{}, fmt.Errorf("%s: an inline object with fields (make it a $def)", ctx)
		}
		return typeInfo{goType: "map[string]any", kind: kMap, elem: &typeInfo{goType: "any"}}, nil
	}
	return typeInfo{}, fmt.Errorf("%s: unsupported schema (type %v)", ctx, node.get("type"))
}

func mapOf(elem typeInfo) (typeInfo, error) {
	if elem.kind == kUnion {
		return typeInfo{}, fmt.Errorf("a map of unions is not supported")
	}
	return typeInfo{goType: "map[string]" + elem.goType, kind: kMap, elem: &elem}, nil
}

func (g *gen) fields(name string, d *object) ([]field, error) {
	props, _ := d.get("properties").(*object)
	required := map[string]bool{}
	for _, r := range requiredOf(d) {
		required[r] = true
	}
	var out []field
	seen := map[string]bool{}
	for _, key := range props.keysOrNil() {
		p, ok := props.get(key).(*object)
		if !ok {
			return nil, fmt.Errorf("field %s is not a schema", key)
		}
		f := field{key: key, name: goName(key), required: required[key]}
		if seen[f.name] {
			return nil, fmt.Errorf("fields collide as %s", f.name)
		}
		seen[f.name] = true
		t, err := g.typeOf(p, name+f.name)
		if err != nil {
			return nil, fmt.Errorf("field %s: %w", key, err)
		}
		f.t = t
		f.def, f.hasDef = p.vals["default"]
		if c, ok := p.get("const").(string); ok {
			f.constVal = c
		}
		if !f.required && !f.hasDef {
			switch t.kind {
			case kScalar, kEnum, kStruct:
				inner := t
				f.t = typeInfo{goType: "*" + t.goType, kind: kPtr, elem: &inner}
			}
			f.omitEmpty = true
		}
		out = append(out, f)
	}
	return out, nil
}

func (o *object) keysOrNil() []string {
	if o == nil {
		return nil
	}
	return o.keys
}

// literal: a Go expression for a non-zero scalar default, or "" when the zero value already is the default.
func literal(f field) (string, error) {
	switch v := f.def.(type) {
	case nil:
		return "", nil
	case bool:
		if v {
			return "true", nil
		}
		return "", nil
	case json.Number:
		if v == "0" || v == "0.0" {
			return "", nil
		}
		if f.t.kind != kScalar {
			return "", fmt.Errorf("a number default for %s", f.t.goType)
		}
		return string(v), nil
	case string:
		if v == "" {
			return "", nil
		}
		if f.t.kind == kEnum {
			return f.t.goType + "(" + strconv.Quote(v) + ")", nil
		}
		if f.t.goType != "string" {
			return "", fmt.Errorf("a string default for %s", f.t.goType)
		}
		return strconv.Quote(v), nil
	case []any:
		if len(v) == 0 && f.t.kind == kSlice {
			return "", nil // encoding turns nil into []
		}
	case *object:
		if len(v.keys) == 0 && f.t.kind == kMap {
			return "", nil // encoding turns nil into {}
		}
	}
	return "", fmt.Errorf("unsupported default %v", plainJSON(f.def))
}

func (g *gen) emitStruct(b *strings.Builder, name string, d *object) error {
	fs, err := g.fields(name, d)
	if err != nil {
		return err
	}
	b.WriteString(comment(name, d.get("description")))
	fmt.Fprintf(b, "type %s struct {\n", name)
	for _, f := range fs {
		tag := f.key
		if f.omitEmpty {
			tag += ",omitempty"
		}
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", f.name, f.t.goType, tag)
	}
	b.WriteString("}\n\n")

	// Decoding: defaults first, then unions through their Decode functions.
	var defaults, unionFields []string
	var unionDecodes []string
	for _, f := range fs {
		lit, err := literal(f)
		if err != nil {
			return fmt.Errorf("field %s: %w", f.key, err)
		}
		if lit != "" {
			defaults = append(defaults, fmt.Sprintf("%s: %s", f.name, lit))
		}
		switch {
		case f.t.kind == kUnion:
			unionFields = append(unionFields, fmt.Sprintf("\t\t%s json.RawMessage `json:%q`", f.name, f.key))
			unionDecodes = append(unionDecodes, fmt.Sprintf(
				"\tif v.%s, err = decodeOne(w.%s, Decode%s); err != nil {\n\t\treturn fmt.Errorf(\"%s.%s: %%w\", err)\n\t}\n",
				f.name, f.name, f.t.union, name, f.key))
		case f.t.kind == kSlice && f.t.elem.kind == kUnion:
			unionFields = append(unionFields, fmt.Sprintf("\t\t%s json.RawMessage `json:%q`", f.name, f.key))
			unionDecodes = append(unionDecodes, fmt.Sprintf(
				"\tif v.%s, err = decodeList(w.%s, Decode%s); err != nil {\n\t\treturn fmt.Errorf(\"%s.%s%%w\", err)\n\t}\n",
				f.name, f.name, f.t.elem.union, name, f.key))
		case f.t.kind == kPtr && f.t.elem.kind == kUnion, f.t.kind == kSlice && f.t.elem.kind != kUnion && f.t.elem.elem != nil && f.t.elem.elem.kind == kUnion:
			return fmt.Errorf("field %s: unsupported nesting of a union", f.key)
		}
	}
	fmt.Fprintf(b, "// New%s gives a %s holding the schema's defaults. Build values to send with it: a field left at\n"+
		"// Go's zero value is sent as that value, not as the server's default.\n", name, name)
	fmt.Fprintf(b, "func New%s() %s {\n\treturn %s{%s}\n}\n\n", name, name, name, strings.Join(defaults, ", "))
	if len(defaults) > 0 || len(unionFields) > 0 {
		fmt.Fprintf(b, "func (v *%s) UnmarshalJSON(data []byte) error {\n\ttype plain %s\n", name, name)
		if len(unionFields) == 0 {
			fmt.Fprintf(b, "\tw := plain(New%s())\n\tif err := json.Unmarshal(data, &w); err != nil {\n\t\treturn err\n\t}\n\t*v = %s(w)\n\treturn nil\n}\n\n",
				name, name)
		} else {
			fmt.Fprintf(b, "\tvar w struct {\n\t\tplain\n%s\n\t}\n", strings.Join(unionFields, "\n"))
			fmt.Fprintf(b, "\tw.plain = plain(New%s())\n", name)
			fmt.Fprintf(b, "\tif err := json.Unmarshal(data, &w); err != nil {\n\t\treturn err\n\t}\n\t*v = %s(w.plain)\n\tvar err error\n", name)
			b.WriteString(strings.Join(unionDecodes, ""))
			b.WriteString("\treturn nil\n}\n\n")
		}
	}

	// Encoding: [] and {} for nil, the const for an empty tag.
	var fills []string
	for _, f := range fs {
		if f.omitEmpty {
			continue
		}
		switch {
		case f.constVal != "":
			fills = append(fills, fmt.Sprintf("\tif p.%s == \"\" {\n\t\tp.%s = %q\n\t}\n", f.name, f.name, f.constVal))
		case f.t.kind == kSlice || f.t.kind == kMap:
			fills = append(fills, fmt.Sprintf("\tif p.%s == nil {\n\t\tp.%s = %s{}\n\t}\n", f.name, f.name, f.t.goType))
		}
	}
	if len(fills) > 0 {
		fmt.Fprintf(b, "func (v %s) MarshalJSON() ([]byte, error) {\n\ttype plain %s\n\tp := plain(v)\n%s\treturn json.Marshal(p)\n}\n\n",
			name, name, strings.Join(fills, ""))
	}
	return nil
}

func (g *gen) emitUnion(b *strings.Builder, u *union) {
	n := u.names
	desc, _ := u.desc.(string)
	if desc == "" {
		desc = "one of " + strings.Join(u.variants, ", ") + "."
	}
	b.WriteString(comment(u.name, desc))
	fmt.Fprintf(b, "type %s interface {\n\t%s\n}\n\n", u.name, n.method)
	method := strings.SplitN(n.method, "(", 2)[0]
	for _, v := range u.variants {
		if strings.HasSuffix(n.method, "string") {
			fmt.Fprintf(b, "func (%s) %s() string { return %q }\n", v, method, u.tags[v])
		} else {
			fmt.Fprintf(b, "func (%s) %s() {}\n", v, method)
		}
	}
	fmt.Fprintf(b, "\n// %s is a %s variant this client does not know (from a newer server): kept as sent, never an error.\n", n.unknown, u.name)
	fmt.Fprintf(b, "type %s struct {\n\t%s string\n\tRaw json.RawMessage\n}\n\n", n.unknown, n.tagField)
	if strings.HasSuffix(n.method, "string") {
		fmt.Fprintf(b, "func (u %s) %s() string { return u.%s }\n\n", n.unknown, method, n.tagField)
	} else {
		fmt.Fprintf(b, "func (%s) %s() {}\n\n", n.unknown, method)
	}
	fmt.Fprintf(b, "// MarshalJSON gives back the JSON as it was received.\nfunc (u %s) MarshalJSON() ([]byte, error) { return rawOrNull(u.Raw), nil }\n\n", n.unknown)

	if u.byShape {
		fmt.Fprintf(b, "// shapes%s: without its tag, a value is the one variant it fits exactly (all its required\n"+
			"// fields, and only fields that variant has); several or none is unknown, never a guess.\n", u.name)
		fmt.Fprintf(b, "var shapes%s = []shape{\n", u.name)
		for _, v := range u.variants {
			d, _ := g.def(v)
			var req, props []string
			for _, r := range requiredOf(d) {
				req = append(req, strconv.Quote(r))
			}
			if po, ok := d.get("properties").(*object); ok {
				for _, k := range po.keys {
					props = append(props, strconv.Quote(k))
				}
			}
			closed := d.get("additionalProperties") == false
			fmt.Fprintf(b, "\t{tag: %q, required: []string{%s}, fields: []string{%s}, closed: %t},\n",
				u.tags[v], strings.Join(req, ", "), strings.Join(props, ", "), closed)
		}
		b.WriteString("}\n\n")
	}
	fmt.Fprintf(b, "// Decode%s decodes one %s; a variant this client does not know is a %s.\n", u.name, u.name, n.unknown)
	fmt.Fprintf(b, "func Decode%s(raw json.RawMessage) (%s, error) {\n", u.name, u.name)
	if u.tagProp != "" {
		fmt.Fprintf(b, "\ttag, err := unionTag(raw, %q)\n\tif err != nil {\n\t\treturn nil, fmt.Errorf(\"%s: %%w\", err)\n\t}\n", u.tagProp, u.name)
		if u.byShape {
			fmt.Fprintf(b, "\tif tag == \"\" {\n\t\ttag = pickByShape(raw, shapes%s)\n\t}\n", u.name)
		}
		b.WriteString("\tswitch tag {\n")
		for _, v := range u.variants {
			fmt.Fprintf(b, "\tcase %q:\n%s", u.tags[v], decodeVariant(v, u.name+" "+u.tags[v]))
		}
		b.WriteString("\t}\n")
		fmt.Fprintf(b, "\treturn %s{%s: tag, Raw: cloneRaw(raw)}, nil\n}\n\n", n.unknown, n.tagField)
		return
	}
	fmt.Fprintf(b, "\tfields, err := unionFields(raw)\n\tif err != nil {\n\t\treturn nil, fmt.Errorf(\"%s: %%w\", err)\n\t}\n", u.name)
	for _, v := range u.variants {
		fmt.Fprintf(b, "\tif _, ok := fields[%q]; ok {\n%s\t}\n", u.markers[v], decodeVariant(v, u.name+" "+v))
	}
	fmt.Fprintf(b, "\treturn %s{Raw: cloneRaw(raw)}, nil\n}\n\n", n.unknown)
}

func indent(code string) string {
	return strings.ReplaceAll(strings.TrimSuffix("\t"+code, "\t"), "\n\t", "\n\t\t")
}

func decodeVariant(v, what string) string {
	return fmt.Sprintf("\t\tvar v %s\n\t\tif err := json.Unmarshal(raw, &v); err != nil {\n\t\t\treturn nil, fmt.Errorf(\"%s: %%w\", err)\n\t\t}\n\t\treturn v, nil\n", v, what)
}

// ---------------------------------------------------------------- constants and methods

func constants(xc any, methodsJSON []byte) (string, error) {
	cs, ok := xc.(*object)
	if !ok || len(cs.keys) == 0 {
		return "", fmt.Errorf("schema.json: no x-constants")
	}
	var b strings.Builder
	b.WriteString(header + "package protocol\n\n// Constants from the schema's x-constants.\nconst (\n")
	var nested, vars []string
	for _, k := range cs.keys {
		v := cs.get(k)
		if o, ok := v.(*object); ok {
			prefix, ok := constantPrefixes[k]
			if !ok {
				prefix = goName(k)
			}
			var inner strings.Builder
			for _, ik := range o.keys {
				iv := o.get(ik)
				if l, ok := iv.([]any); ok {
					lit, err := stringsLiteral(l)
					if err != nil {
						return "", fmt.Errorf("x-constants %s.%s: %w", k, ik, err)
					}
					vars = append(vars, fmt.Sprintf("var %s%s = %s // %s.%s\n", prefix, goName(ik), lit, k, ik))
					continue
				}
				lit, err := constLiteral(iv)
				if err != nil {
					return "", fmt.Errorf("x-constants %s.%s: %w", k, ik, err)
				}
				fmt.Fprintf(&inner, "\t%s%s = %s\n", prefix, goName(ik), lit)
			}
			if inner.Len() > 0 {
				nested = append(nested, fmt.Sprintf("// %s\nconst (\n%s)\n\n", k, inner.String()))
			}
			continue
		}
		if l, ok := v.([]any); ok {
			lit, err := stringsLiteral(l)
			if err != nil {
				return "", fmt.Errorf("x-constants %s: %w", k, err)
			}
			vars = append(vars, fmt.Sprintf("var %s = %s // %s\n", goName(k), lit, k))
			continue
		}
		lit, err := constLiteral(v)
		if err != nil {
			return "", fmt.Errorf("x-constants %s: %w", k, err)
		}
		fmt.Fprintf(&b, "\t%s = %s // %s\n", goName(k), lit, k)
		if a, ok := constantAliases[k]; ok {
			fmt.Fprintf(&b, "\t%s = %s // %s\n", a.name, goName(k), a.doc)
		}
	}
	b.WriteString(")\n\n")
	for _, n := range nested {
		b.WriteString(n)
	}
	if len(vars) > 0 {
		b.WriteString("// Lists from the schema's x-constants. Go has no constant slices: never change them.\n")
		for _, v := range vars {
			b.WriteString(v)
		}
		b.WriteString("\n")
	}

	root, err := parseOrdered(methodsJSON)
	if err != nil {
		return "", fmt.Errorf("methods.json: %w", err)
	}
	ms, ok := root.(*object)
	if !ok || len(ms.keys) == 0 {
		return "", fmt.Errorf("methods.json: no methods")
	}
	b.WriteString("// Method is one RPC method: who may call it and the $defs of its params and result.\n")
	b.WriteString("type Method struct {\n\tName, Who, Params, Result string\n}\n\n")
	b.WriteString("// Methods are the server's RPC methods by name.\nvar Methods = map[string]Method{\n")
	for _, name := range ms.keys {
		m, ok := ms.get(name).(*object)
		if !ok {
			return "", fmt.Errorf("methods.json: %s is not an object", name)
		}
		var parts [3]string
		for i, k := range []string{"who", "params", "result"} {
			s, ok := m.get(k).(string)
			if !ok || s == "" {
				return "", fmt.Errorf("methods.json: %s has no %s", name, k)
			}
			parts[i] = s
		}
		fmt.Fprintf(&b, "\t%q: {Name: %q, Who: %q, Params: %q, Result: %q},\n", name, name, parts[0], parts[1], parts[2])
	}
	b.WriteString("}\n")
	return b.String(), nil
}

// stringsLiteral maps a list constant: only a list of strings is supported.
func stringsLiteral(l []any) (string, error) {
	items := make([]string, len(l))
	for i, e := range l {
		x, ok := e.(string)
		if !ok {
			return "", fmt.Errorf("unsupported constant %v: a list must hold only strings", plainJSON(l))
		}
		items[i] = strconv.Quote(x)
	}
	return "[]string{" + strings.Join(items, ", ") + "}", nil
}

func constLiteral(v any) (string, error) {
	switch x := v.(type) {
	case json.Number:
		return string(x), nil
	case string:
		return strconv.Quote(x), nil
	case bool:
		return strconv.FormatBool(x), nil
	}
	return "", fmt.Errorf("unsupported constant %v", plainJSON(v))
}
